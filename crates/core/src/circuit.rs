//! A view as a DBSP circuit: the operator graph built from a compiled view, the pass that makes it incremental,
//! and the SQL one epoch runs.
//!
//! The graph follows Feldera's: operators in topological order, each reading output ports of earlier ones.
//! `Circuit::query` is the view as a query over whole collections (Q). `incrementalize` turns it into the
//! circuit that runs on changes, the way DBSP proves it can be done: wrap the query as D ∘ Q ∘ I (integrate
//! each source's changes into a collection, differentiate each result back into changes), then rewrite.
//!
//! The rewrite is Feldera's (`OptimizeIncrementalVisitor`): integrators only move forward.
//!
//! - A linear operator L (map, filter, window assignment, the late split) commutes with I: L ∘ I = I ∘ L.
//! - Any other operator S becomes its incremental form SΔ = D ∘ S ∘ I, so S ∘ I = I ∘ SΔ. SΔ keeps its state
//!   in a DuckLake table.
//! - Where an integrator reaches a differentiator they cancel: D ∘ I = id.
//!
//! What is left has no I or D: linear operators on changes plus incremental operators with state. State lives
//! only where the algebra needs it. Every operator's SQL is generated by `stage_steps` (in-memory staging,
//! before the epoch's transaction) and `commit_steps` (writes in the transaction). Linear operators fuse into
//! their consumer's statement where they can; the stateless SQL fragments the view compiler produces from
//! DuckDB's parse tree read named tables, so their inputs are materialized under those names.
use crate::catalog::state_table;
use crate::lake::{ident, quote_table};
use crate::model::JobDef;
use crate::plan::{AggKind, GlobalTables, Plan, WindowKind, WindowSpec};
use anyhow::Result;
use std::fmt::{self, Write};

#[derive(Debug, Clone, PartialEq)]
pub enum Op {
    /// The source's rows, each with its weight `__w`. In Q the whole collection; after incrementalization the
    /// epoch's new rows.
    Source(String),
    /// TUMBLE or HOP: one row per window a row falls in, with `window_start` and `window_end`.
    Window(WindowSpec),
    /// Port 0: rows of windows still open at the previous watermark. Port 1: late rows of windows already closed.
    LateSplit,
    /// A stateless fragment of the view: projection, filter, lookup joins.
    Map(Fragment),
    /// Grouped aggregation. Windowed: partials per window and group, emitted once the watermark closes the
    /// window. Global: one row per group, replaced when it changes.
    Aggregate(Grouping),
    Integrate,
    Differentiate,
    /// The incremental aggregate `D ∘ Aggregate ∘ I`, with a DuckLake state table.
    AggregateDelta(Grouping),
    Sink(SinkKind),
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Fragment {
    /// The whole view of a stateless view.
    View,
    /// A global aggregate's FROM/WHERE: group keys, aggregate arguments and weights.
    PreAggregate,
    /// A global aggregate's HAVING and select list over the finalized groups.
    PostAggregate,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Grouping {
    Windowed,
    Global,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum SinkKind {
    /// The view's table, rows only ever added.
    Append,
    /// The view's table, one row per group, replaced when it changes.
    Upsert,
    /// The late-data table.
    Late,
}

impl Op {
    /// Linear operators commute with integration and differentiation: they need no state.
    pub fn is_linear(&self) -> bool {
        matches!(self, Op::Window(_) | Op::LateSplit | Op::Map(_))
    }

    fn outputs(&self) -> usize {
        match self {
            Op::LateSplit => 2,
            Op::Sink(_) => 0,
            _ => 1,
        }
    }

    fn name(&self) -> String {
        match self {
            Op::Source(s) => format!("Source({s})"),
            Op::Window(w) => {
                let secs = |us: i64| format!("{}s", us / 1_000_000);
                match w.kind {
                    WindowKind::Tumble => format!("Window(TUMBLE {}, {})", w.time_col, secs(w.size_us)),
                    WindowKind::Hop => format!("Window(HOP {}, {} every {})", w.time_col, secs(w.size_us), secs(w.slide_us)),
                }
            }
            Op::LateSplit => "LateSplit(on time | late)".into(),
            Op::Map(f) => format!("Map({})", match f {
                Fragment::View => "view",
                Fragment::PreAggregate => "pre-aggregate",
                Fragment::PostAggregate => "post-aggregate",
            }),
            Op::Aggregate(g) => format!("Aggregate({})", grouping(*g)),
            Op::Integrate => "I".into(),
            Op::Differentiate => "D".into(),
            Op::AggregateDelta(g) => format!("AggregateΔ({}) [state table]", grouping(*g)),
            Op::Sink(k) => format!("Sink({})", match k {
                SinkKind::Append => "append",
                SinkKind::Upsert => "upsert",
                SinkKind::Late => "late data",
            }),
        }
    }
}

fn grouping(g: Grouping) -> &'static str {
    match g {
        Grouping::Windowed => "windowed, emit on close",
        Grouping::Global => "global",
    }
}

/// An output port of a node.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Port {
    pub node: usize,
    pub port: usize,
}

/// What the analyses know about a node's output.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct Props {
    /// No row with weight −1 can reach it: rows are only ever added.
    pub append_only: bool,
}

#[derive(Debug, Clone)]
pub struct Node {
    pub op: Op,
    pub inputs: Vec<Port>,
    pub props: Props,
}

#[derive(Debug, Clone, Default)]
pub struct Circuit {
    /// In topological order: a node reads only earlier nodes.
    pub nodes: Vec<Node>,
    /// The rewrites `incrementalize` applied, in order.
    pub trace: Vec<String>,
    /// True once the circuit runs on changes.
    pub incremental: bool,
}

impl Circuit {
    /// Adds a node; until `analyze` runs, it has its first input's properties.
    fn add(&mut self, op: Op, inputs: Vec<Port>) -> Port {
        let props = inputs.first().map(|p| self.nodes[p.node].props).unwrap_or_default();
        self.nodes.push(Node { op, inputs, props });
        Port { node: self.nodes.len() - 1, port: 0 }
    }

    /// Q: the view as a query over whole collections, built from the compiled plan.
    pub fn query(plan: &Plan, def: &JobDef) -> Circuit {
        let mut c = Circuit::default();
        let src = c.add(Op::Source(plan.source.clone()), vec![]);
        // Kafka without CDC: every message is an insert.
        c.nodes[src.node].props.append_only = true;
        if let Some(w) = &plan.window {
            let win = c.add(Op::Window(w.clone()), vec![src]);
            let split = c.add(Op::LateSplit, vec![win]).node;
            let agg = c.add(Op::Aggregate(Grouping::Windowed), vec![Port { node: split, port: 0 }]);
            c.add(Op::Sink(SinkKind::Append), vec![agg]);
            if def.late_data.is_some() {
                c.add(Op::Sink(SinkKind::Late), vec![Port { node: split, port: 1 }]);
            }
        } else if plan.global.is_some() {
            let pre = c.add(Op::Map(Fragment::PreAggregate), vec![src]);
            let agg = c.add(Op::Aggregate(Grouping::Global), vec![pre]);
            let post = c.add(Op::Map(Fragment::PostAggregate), vec![agg]);
            c.add(Op::Sink(SinkKind::Upsert), vec![post]);
        } else {
            let view = c.add(Op::Map(Fragment::View), vec![src]);
            c.add(Op::Sink(SinkKind::Append), vec![view]);
        }
        c.analyze();
        c
    }

    /// The circuit of `plan` that runs every epoch.
    pub fn compile(plan: &Plan, def: &JobDef) -> Result<Circuit> {
        let q = Circuit::query(plan, def);
        q.check(plan)?;
        Ok(q.incrementalize())
    }

    /// Fills in each node's properties from its inputs', in topological order. Sources keep theirs.
    pub fn analyze(&mut self) {
        for n in 0..self.nodes.len() {
            let inputs_append_only = self.nodes[n].inputs.iter().all(|p| self.nodes[p.node].props.append_only);
            self.nodes[n].props.append_only = match self.nodes[n].op {
                Op::Source(_) => continue,
                // A group's row is replaced when the group changes: the old one is retracted.
                Op::Aggregate(Grouping::Global) | Op::AggregateDelta(Grouping::Global) => false,
                // Linear operators keep retractions as they are, and a windowed aggregate emits each window
                // once, when it closes, so its output retracts only if its input does.
                _ => inputs_append_only,
            };
        }
    }

    /// Refuses a circuit where an operator implemented for append-only input reads a stream that can retract.
    pub fn check(&self, plan: &Plan) -> Result<()> {
        let min_max = plan.global.as_ref().is_some_and(|g| g.aggs.iter().any(|a| matches!(a.kind, AggKind::Min | AggKind::Max)));
        for node in &self.nodes {
            if node.inputs.iter().all(|p| self.nodes[p.node].props.append_only) {
                continue;
            }
            let assumes = match node.op {
                Op::Aggregate(Grouping::Windowed) | Op::AggregateDelta(Grouping::Windowed) => {
                    Some("a windowed aggregate's partials ignore weights")
                }
                Op::Aggregate(Grouping::Global) | Op::AggregateDelta(Grouping::Global) if min_max => {
                    Some("MIN and MAX keep one value per group")
                }
                Op::Sink(SinkKind::Append) | Op::Sink(SinkKind::Late) => Some("an append sink only inserts"),
                _ => None,
            };
            if let Some(why) = assumes {
                anyhow::bail!("{} reads a stream that can retract rows, but {why}: not supported yet", node.op.name());
            }
        }
        Ok(())
    }

    /// Readers of `p`: (node, input slot).
    fn readers(&self, p: Port, dead: &[bool]) -> Vec<(usize, usize)> {
        let mut out = Vec::new();
        for (n, node) in self.nodes.iter().enumerate() {
            if dead[n] {
                continue;
            }
            for (slot, i) in node.inputs.iter().enumerate() {
                if *i == p {
                    out.push((n, slot));
                }
            }
        }
        out
    }

    fn redirect(&mut self, from: Port, to: Port, except: Option<usize>, dead: &[bool]) {
        for (n, slot) in self.readers(from, dead) {
            if Some(n) != except {
                self.nodes[n].inputs[slot] = to;
            }
        }
    }

    /// D ∘ Q ∘ I, rewritten until no integrator or differentiator is left (see the module docs).
    pub fn incrementalize(mut self) -> Circuit {
        let mut dead = vec![false; self.nodes.len()];
        let mut trace = Vec::new();
        // Wrap: an integrator after every source, a differentiator before every sink.
        for n in 0..self.nodes.len() {
            if let Op::Source(s) = &self.nodes[n].op {
                let s = s.clone();
                let out = Port { node: n, port: 0 };
                let i = self.add(Op::Integrate, vec![out]);
                dead.push(false);
                self.redirect(out, i, Some(i.node), &dead);
                trace.push(format!("wrap: Source({s}) now emits the epoch's changes; I integrates them"));
            }
        }
        for n in 0..self.nodes.len() {
            if let Op::Sink(_) = self.nodes[n].op {
                let input = self.nodes[n].inputs[0];
                let d = self.add(Op::Differentiate, vec![input]);
                dead.push(false);
                self.nodes[n].inputs[0] = d;
                trace.push(format!("wrap: D before {}", self.nodes[n].op.name()));
            }
        }
        // Push every integrator forward, as Feldera's OptimizeIncrementalVisitor does, until it meets a
        // differentiator: an operator whose input is integrated runs on the changes instead, followed by an
        // integrator on each of its outputs.
        loop {
            let mut changed = false;
            for n in 0..self.nodes.len() {
                if dead[n] || self.nodes[n].inputs.is_empty() {
                    continue;
                }
                let input = self.nodes[n].inputs[0];
                if self.nodes[input.node].op != Op::Integrate {
                    continue;
                }
                let op = self.nodes[n].op.clone();
                let rule = match &op {
                    // D ∘ I = id.
                    Op::Differentiate => {
                        let x = self.nodes[input.node].inputs[0];
                        let sinks: Vec<String> = self.readers(Port { node: n, port: 0 }, &dead).iter().map(|(r, _)| self.nodes[*r].op.name()).collect();
                        self.redirect(Port { node: n, port: 0 }, x, None, &dead);
                        dead[n] = true;
                        format!("D ∘ I = id before {}", sinks.join(", "))
                    }
                    // L ∘ I = I ∘ L.
                    l if l.is_linear() => format!("{} ∘ I = I ∘ {0}: it is linear", l.name()),
                    // S ∘ I = I ∘ SΔ: the operator's incremental form, by definition SΔ = D ∘ S ∘ I.
                    Op::Aggregate(g) => {
                        self.nodes[n].op = Op::AggregateDelta(*g);
                        format!("{} ∘ I = I ∘ {}: state in a DuckLake table", op.name(), self.nodes[n].op.name().replace(" [state table]", ""))
                    }
                    _ => continue,
                };
                if op != Op::Differentiate {
                    self.nodes[n].inputs[0] = self.nodes[input.node].inputs[0];
                    for port in 0..op.outputs() {
                        let out = Port { node: n, port };
                        let i = self.add(Op::Integrate, vec![out]);
                        dead.push(false);
                        self.redirect(out, i, Some(i.node), &dead);
                    }
                }
                if self.readers(input, &dead).is_empty() {
                    dead[input.node] = true;
                }
                trace.push(rule);
                changed = true;
                break;
            }
            if !changed {
                break;
            }
        }
        // Like Feldera's NoIntegralVisitor: anything left needs an operator the rules do not know.
        if let Some(n) = (0..self.nodes.len()).find(|n| !dead[*n] && matches!(self.nodes[*n].op, Op::Integrate | Op::Differentiate)) {
            trace.push(format!("left over: {} at n{n}", self.nodes[n].op.name()));
        }
        let mut out = self.compact(&dead);
        out.trace = trace;
        out.incremental = true;
        out
    }

    /// Drops dead nodes and renumbers the rest in topological order.
    fn compact(&self, dead: &[bool]) -> Circuit {
        let live: Vec<usize> = (0..self.nodes.len()).filter(|n| !dead[*n]).collect();
        let mut order = Vec::new();
        let mut placed = vec![false; self.nodes.len()];
        while order.len() < live.len() {
            for &n in &live {
                if !placed[n] && self.nodes[n].inputs.iter().all(|p| placed[p.node]) {
                    placed[n] = true;
                    order.push(n);
                }
            }
        }
        let new_id = |old: usize| order.iter().position(|n| *n == old).unwrap();
        let nodes = order
            .iter()
            .map(|&n| Node {
                op: self.nodes[n].op.clone(),
                inputs: self.nodes[n].inputs.iter().map(|p| Port { node: new_id(p.node), port: p.port }).collect(),
                props: self.nodes[n].props,
            })
            .collect();
        Circuit { nodes, trace: Vec::new(), incremental: false }
    }

    fn has(&self, op: &Op) -> bool {
        self.nodes.iter().any(|n| &n.op == op)
    }

    /// Windowed aggregates emit a window only once the watermark closes it.
    pub fn emits_final(&self) -> bool {
        self.has(&Op::AggregateDelta(Grouping::Windowed))
    }

    /// Whether the output rows are the changed groups (an upsert sink) rather than rows inserted.
    pub fn upserts(&self) -> bool {
        self.has(&Op::Sink(SinkKind::Upsert))
    }

    /// The SQL of one epoch's staging, in order: in-memory tables only, nothing touches the lake.
    pub fn stage_steps(&self, x: &EpochCtx) -> Result<Vec<Step>> {
        let mut steps = Vec::new();
        let plan = x.plan;
        let cols = x.source_columns.iter().map(|(c, _)| ident(c)).collect::<Vec<_>>().join(", ");
        let set = format!("{}_{}", x.job, x.parity);
        // The relation each node's output port reads as (a subquery when fused, else a table).
        let mut rel: Vec<Vec<String>> = vec![Vec::new(); self.nodes.len()];
        for (n, node) in self.nodes.iter().enumerate() {
            let input = |k: usize| rel[node.inputs[k].node][node.inputs[k].port].clone();
            match &node.op {
                Op::Source(_) => {
                    // Kafka rows are inserts: weight +1.
                    rel[n] = vec![format!("(SELECT _partition, _offset, {cols}, 1::INTEGER AS __w FROM {} WHERE _err IS NULL)", x.typed)];
                }
                Op::Window(_) => {
                    // Read twice by the late split, so materialized.
                    let win = staging("win", x.job);
                    steps.push(Step::stage(format!("CREATE OR REPLACE TABLE {win} AS {}", plan.window_sql(&input(0)))));
                    rel[n] = vec![win];
                }
                Op::LateSplit => {
                    let (late, prev) = (staging("late", &set), &x.prev_watermark);
                    steps.push(
                        Step::stage(format!("CREATE OR REPLACE TABLE {late} AS SELECT * FROM {} WHERE window_end <= {prev}", input(0)))
                            .counting(Counter::Late, &late),
                    );
                    rel[n] = vec![
                        format!(
                            "(SELECT {cols}, __w, window_start, window_end FROM {} WHERE {prev} IS NULL OR window_end > {prev})",
                            input(0)
                        ),
                        late,
                    ];
                }
                Op::Map(Fragment::View) | Op::Map(Fragment::PreAggregate) => {
                    // The fragment reads the view's input table: materialize this operator's input under that name,
                    // with the source's columns only (and the weights, which the pre-aggregate sums). An append sink
                    // writes the view's rows as they are: `check` makes sure none of them is a retraction.
                    let keep = if node.op == Op::Map(Fragment::View) { cols.clone() } else { format!("{cols}, __w") };
                    let input = format!("SELECT {keep} FROM {}", input(0));
                    steps.push(Step::stage(format!("CREATE OR REPLACE TABLE {} AS {input}", plan.input_table)));
                    if node.op == Op::Map(Fragment::View) {
                        let out = staging("out", &set);
                        steps.push(Step::stage(format!("CREATE OR REPLACE TABLE {out} AS {}", plan.delta_sql)).counting(Counter::Staged, &out));
                        rel[n] = vec![out];
                    } else {
                        let t = x.global_tables()?;
                        steps.push(Step::stage(plan.global.as_ref().unwrap().pre_stmt(&t)));
                        rel[n] = vec![t.pre.clone()];
                    }
                }
                Op::AggregateDelta(Grouping::Windowed) => {
                    // The epoch's partials per window and group; reads the on-time rows as the view's input.
                    steps.push(Step::stage(format!("CREATE OR REPLACE TABLE {} AS {}", plan.input_table, query(&input(0)))));
                    let out = staging("out", &set);
                    steps.push(Step::stage(format!("CREATE OR REPLACE TABLE {out} AS {}", plan.delta_sql)).counting(Counter::Staged, &out));
                    rel[n] = vec![out];
                }
                Op::AggregateDelta(Grouping::Global) => {
                    let g = plan.global.as_ref().unwrap();
                    let mut t = x.global_tables()?;
                    if let Some(prev) = x.overlay {
                        // The previous epoch may still be committing: read its new state for the groups it touched.
                        let prev_new = GlobalTables::new(x.job, state_table(x.job), String::new(), plan, prev).new_state;
                        t.state = g.overlay_sql(&t.state, &prev_new, &plan.state_columns);
                    }
                    let stmts = g.aggregate_stmts(&t, &plan.state_columns);
                    for (k, s) in stmts.into_iter().enumerate() {
                        let step = Step::stage(s);
                        steps.push(if k == 0 { step.counting(Counter::Staged, &t.delta) } else { step });
                    }
                    rel[n] = vec![t.new_state.clone()];
                }
                Op::Map(Fragment::PostAggregate) => {
                    let t = x.global_tables()?;
                    steps.extend(plan.global.as_ref().unwrap().post_stmts(&t).into_iter().map(Step::stage));
                    rel[n] = vec![t.new_out.clone()];
                }
                Op::Sink(SinkKind::Upsert) => {
                    let t = x.global_tables()?;
                    let stmts = plan.global.as_ref().unwrap().upsert_stmts(&t);
                    for (k, s) in stmts.into_iter().enumerate() {
                        let step = Step::stage(s);
                        steps.push(if k == 0 { step.counting(Counter::Changed, &t.changed) } else { step });
                    }
                }
                Op::Sink(_) => {}
                Op::Aggregate(_) | Op::Integrate | Op::Differentiate => {
                    anyhow::bail!("{} left in the epoch circuit: incrementalize it first", node.op.name())
                }
            }
        }
        Ok(steps)
    }

    /// The SQL of one epoch's writes, in the epoch transaction, in order.
    pub fn commit_steps(&self, x: &EpochCtx) -> Result<Vec<Step>> {
        let mut steps = Vec::new();
        let plan = x.plan;
        let set = format!("{}_{}", x.job, x.parity);
        let sink_cols: Vec<String> = plan.sink_columns.iter().map(|(c, _)| ident(c)).chain(["_duckwake_epoch".into()]).collect();
        let sink_cols = sink_cols.join(", ");
        for node in &self.nodes {
            match &node.op {
                Op::AggregateDelta(Grouping::Windowed) => {
                    let st = state_table(x.job);
                    steps.push(
                        Step::commit(plan.merge_sql(&st, &staging("out", &set)), Cost::State).skip_if_none(Counter::Staged).crash_after(),
                    );
                    if let Some(wm) = &x.watermark {
                        // Emit the windows the watermark closed, then drop them from the state.
                        steps.push(
                            Step::commit(
                                format!(
                                    "INSERT INTO {} ({sink_cols}) SELECT {}, {} FROM {st} WHERE __we <= {wm}",
                                    x.sink, plan.final_select, x.epoch
                                ),
                                Cost::Sink,
                            )
                            .output_rows()
                            .needs_close(),
                        );
                        steps.push(Step::commit(format!("DELETE FROM {st} WHERE __we <= {wm}"), Cost::State).needs_close());
                    }
                }
                Op::AggregateDelta(Grouping::Global) => {
                    let t = x.global_tables()?;
                    let stmts = plan.global.as_ref().unwrap().commit_state_sql(&t, &plan.state_columns);
                    let last = stmts.len() - 1;
                    for (k, s) in stmts.into_iter().enumerate() {
                        let step = Step::commit(s, Cost::State).skip_if_none(Counter::Staged);
                        steps.push(if k == last { step.crash_after() } else { step });
                    }
                }
                Op::Sink(SinkKind::Upsert) => {
                    let t = x.global_tables()?;
                    for s in plan.global.as_ref().unwrap().commit_sink_sql(&t, &x.epoch) {
                        steps.push(Step::commit(s, Cost::Sink).skip_if_none(Counter::Changed));
                    }
                }
                Op::Sink(SinkKind::Append) if !self.emits_final() => {
                    steps.push(
                        Step::commit(
                            format!("INSERT INTO {} ({sink_cols}) SELECT *, {} FROM {}", x.sink, x.epoch, staging("out", &set)),
                            Cost::Sink,
                        )
                        .skip_if_none(Counter::Staged)
                        .output_rows()
                        .crash_after(),
                    );
                }
                Op::Sink(SinkKind::Late) => {
                    let Some(late) = &x.late_table else { continue };
                    let cols = x.source_columns.iter().map(|(c, _)| ident(c)).collect::<Vec<_>>().join(", ");
                    steps.push(
                        Step::commit(
                            format!(
                                "INSERT INTO {late} ({cols}, window_start, window_end, _source_partition, _source_offset, _duckwake_epoch)
                                 SELECT {cols}, window_start, window_end, _partition, _offset, {} FROM {}",
                                x.epoch,
                                staging("late", &set)
                            ),
                            Cost::Late,
                        )
                        .skip_if_none(Counter::Late),
                    );
                }
                _ => {}
            }
        }
        Ok(steps)
    }
}

impl fmt::Display for Circuit {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (n, node) in self.nodes.iter().enumerate() {
            let inputs: Vec<String> = node
                .inputs
                .iter()
                .map(|p| if self.nodes[p.node].op.outputs() > 1 { format!("n{}.{}", p.node, p.port) } else { format!("n{}", p.node) })
                .collect();
            let mut line = format!("  n{n:<2} {}", node.op.name());
            if !inputs.is_empty() {
                let pad = 48usize.saturating_sub(line.chars().count()).max(1);
                let _ = write!(line, "{}← {}", " ".repeat(pad), inputs.join(", "));
            }
            let pad = 62usize.saturating_sub(line.chars().count()).max(2);
            let _ = write!(line, "{}{}", " ".repeat(pad), if node.props.append_only { "append-only" } else { "retracts" });
            writeln!(f, "{line}")?;
        }
        Ok(())
    }
}

/// What one epoch's SQL needs to know.
pub struct EpochCtx<'a> {
    pub job: &'a str,
    pub plan: &'a Plan,
    /// The view's table and its late-data table, quoted.
    pub sink: String,
    pub late_table: Option<String>,
    pub source_columns: &'a [(String, String)],
    /// The epoch's decoded rows of the view's source.
    pub typed: String,
    /// Which of the two table sets this epoch stages into, and the previous epoch's set when a global aggregate
    /// reads that epoch's new state before it has committed.
    pub parity: u64,
    pub overlay: Option<u64>,
    /// SQL expressions: the watermark before and after this epoch (NULL / None before the first), the epoch.
    pub prev_watermark: String,
    pub watermark: Option<String>,
    pub epoch: String,
}

impl EpochCtx<'_> {
    fn global_tables(&self) -> Result<GlobalTables> {
        Ok(GlobalTables::new(self.job, state_table(self.job), self.sink.clone(), self.plan, self.parity))
    }

    /// A context with placeholders instead of values, for showing the SQL.
    pub fn example<'a>(def: &'a JobDef, source_columns: &'a [(String, String)]) -> Result<EpochCtx<'a>> {
        Ok(EpochCtx {
            job: &def.job_id,
            plan: &def.plan,
            sink: quote_table(&def.sink)?,
            late_table: def.late_data.as_deref().map(quote_table).transpose()?,
            source_columns,
            typed: staging("typed", "g0"),
            parity: 1,
            overlay: None,
            prev_watermark: "<previous watermark>".into(),
            watermark: Some("<watermark>".into()),
            epoch: "<epoch>".into(),
        })
    }
}

/// A relation as a query: a fused subquery unwrapped, a table read whole.
fn query(rel: &str) -> String {
    match rel.strip_prefix('(').and_then(|r| r.strip_suffix(')')) {
        Some(q) => q.to_string(),
        None => format!("SELECT * FROM {rel}"),
    }
}

/// An in-memory staging table.
pub fn staging(name: &str, key: &str) -> String {
    format!("memory.main.{}", ident(&format!("{name}_{key}")))
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Counter {
    /// Late rows routed to the late-data table.
    Late,
    /// Rows the commit would write from staging: partials, touched groups, or sink rows.
    Staged,
    /// Groups whose row in an upsert sink changes.
    Changed,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Cost {
    Stage,
    State,
    Sink,
    Late,
}

/// One SQL statement of an epoch, with what the engine does around it.
#[derive(Debug, Clone)]
pub struct Step {
    pub sql: String,
    pub cost: Cost,
    /// Count this table's rows after the step.
    pub count: Option<(Counter, String)>,
    /// With a lean commit, skip the step when this count is 0.
    pub skip_if_none: Option<Counter>,
    /// With a lean commit, skip the step unless a window closes this epoch.
    pub needs_close: bool,
    /// The statement's row count is the view's output rows.
    pub output_rows: bool,
    /// The crash tests' `commit_mid` point follows this step.
    pub crash_after: bool,
}

impl Step {
    fn stage(sql: String) -> Step {
        Step { sql, cost: Cost::Stage, count: None, skip_if_none: None, needs_close: false, output_rows: false, crash_after: false }
    }
    fn commit(sql: String, cost: Cost) -> Step {
        Step { cost, ..Step::stage(sql) }
    }
    fn counting(mut self, c: Counter, table: &str) -> Step {
        self.count = Some((c, table.to_string()));
        self
    }
    fn skip_if_none(mut self, c: Counter) -> Step {
        self.skip_if_none = Some(c);
        self
    }
    fn needs_close(mut self) -> Step {
        self.needs_close = true;
        self
    }
    fn output_rows(mut self) -> Step {
        self.output_rows = true;
        self
    }
    fn crash_after(mut self) -> Step {
        self.crash_after = true;
        self
    }
}

/// The circuit, how it was derived, and one epoch's SQL, as text (`duckwake explain`, `duckwake_explain`).
pub fn explain(def: &JobDef, source_columns: &[(String, String)]) -> Result<String> {
    let q = Circuit::query(&def.plan, def);
    q.check(&def.plan)?;
    let c = q.clone().incrementalize();
    let x = EpochCtx::example(def, source_columns)?;
    let mut out = String::new();
    let _ = writeln!(out, "view {} ({}), table {}\n", def.job_id, def.plan.kind_name(), def.sink);
    let _ = writeln!(out, "Q: the view over whole collections\n{q}");
    let _ = writeln!(out, "Incrementalization: D ∘ Q ∘ I, rewritten");
    for (k, t) in c.trace.iter().enumerate() {
        let _ = writeln!(out, "  {:>2}. {t}", k + 1);
    }
    let _ = writeln!(out, "\nThe circuit that runs every epoch (inputs and outputs are changes)\n{c}");
    let _ = writeln!(out, "One epoch's SQL (staging in memory, then the writes in the epoch transaction)");
    for (k, s) in c.stage_steps(&x)?.iter().enumerate() {
        let _ = writeln!(out, "  stage {}: {}", k + 1, squash(&s.sql));
    }
    for (k, s) in c.commit_steps(&x)?.iter().enumerate() {
        let _ = writeln!(out, "  commit {}: {}", k + 1, squash(&s.sql));
    }
    Ok(out)
}

fn squash(sql: &str) -> String {
    sql.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::SourceOptions;
    use duckdb::Connection;
    use serde_json::json;
    use std::collections::HashMap;

    fn def_for(sql: &str, late: bool) -> JobDef {
        let conn = Connection::open_in_memory().unwrap();
        conn.execute_batch("CREATE TABLE games (game_id VARCHAR, studio VARCHAR)").unwrap();
        let opts = SourceOptions::from_json(&json!({
            "brokers": "x", "topic": "clicks", "event_time": "ts",
            "columns": {"ts": "TIMESTAMP", "game_id": "VARCHAR", "user_id": "VARCHAR", "amount": "DECIMAL(18,2)"}
        }))
        .unwrap();
        let src = crate::model::SourceDef { name: "clicks".into(), kind: "kafka".into(), options: opts };
        let plan = crate::plan::compile(&conn, "v", sql, &HashMap::from([("clicks".to_string(), src)])).unwrap();
        JobDef {
            job_id: "v".into(),
            sql: sql.into(),
            sink: "lake.analytics.v".into(),
            late_data: late.then(|| "lake.analytics.v_late".into()),
            checkpoint: "ducklake".into(),
            epoch_interval: "1s".into(),
            max_rows: 1000,
            inline_row_limit: 10,
            plan,
        }
    }

    fn ops(c: &Circuit) -> Vec<String> {
        c.nodes.iter().map(|n| n.op.name()).collect()
    }

    #[test]
    fn stateless_view_needs_no_state() {
        let def = def_for("SELECT ts, amount FROM clicks WHERE amount > 10", false);
        let c = Circuit::compile(&def.plan, &def).unwrap();
        assert_eq!(ops(&c), ["Source(clicks)", "Map(view)", "Sink(append)"]);
        assert!(c.trace.iter().any(|t| t.contains("D ∘ I = id")), "{:?}", c.trace);
    }

    #[test]
    fn windowed_aggregate_keeps_state_and_routes_late_rows() {
        let def = def_for("SELECT window_start, game_id, count(*) AS n FROM TUMBLE(clicks, ts, INTERVAL 10 SECOND) GROUP BY ALL", true);
        let c = Circuit::compile(&def.plan, &def).unwrap();
        assert_eq!(
            ops(&c),
            [
                "Source(clicks)",
                "Window(TUMBLE ts, 10s)",
                "LateSplit(on time | late)",
                "AggregateΔ(windowed, emit on close) [state table]",
                "Sink(append)",
                "Sink(late data)"
            ]
        );
        assert!(!c.has(&Op::Integrate) && !c.has(&Op::Differentiate));
        assert!(c.emits_final());
    }

    #[test]
    fn global_aggregate_becomes_an_incremental_aggregate_between_linear_maps() {
        let def = def_for("SELECT game_id, count(*) AS n, sum(amount) AS s FROM clicks GROUP BY ALL HAVING count(*) > 1", false);
        let c = Circuit::compile(&def.plan, &def).unwrap();
        assert_eq!(
            ops(&c),
            ["Source(clicks)", "Map(pre-aggregate)", "AggregateΔ(global) [state table]", "Map(post-aggregate)", "Sink(upsert)"]
        );
        assert!(c.upserts());
        // Append-only Kafka rows in, a stream that replaces group rows out.
        let append_only: Vec<bool> = c.nodes.iter().map(|n| n.props.append_only).collect();
        assert_eq!(append_only, [true, true, false, false, false]);
        // The generated SQL is the same set of statements the engine ran before the circuit existed.
        let cols = vec![("ts".to_string(), "TIMESTAMP".to_string())];
        let x = EpochCtx::example(&def, &cols).unwrap();
        let g = def.plan.global.as_ref().unwrap();
        let t = GlobalTables::new("v", state_table("v"), quote_table(&def.sink).unwrap(), &def.plan, 1);
        let stage: Vec<String> = c.stage_steps(&x).unwrap().into_iter().map(|s| s.sql).skip(1).collect();
        assert_eq!(stage, g.stage_sql(&t, &def.plan.state_columns));
        let commit: Vec<String> = c.commit_steps(&x).unwrap().into_iter().map(|s| s.sql).collect();
        assert_eq!(commit, [g.commit_state_sql(&t, &def.plan.state_columns), g.commit_sink_sql(&t, "<epoch>")].concat());
    }

    #[test]
    fn retracting_input_is_refused_where_an_operator_assumes_append_only() {
        let refused = [
            "SELECT window_start, game_id, count(*) AS n FROM TUMBLE(clicks, ts, INTERVAL 10 SECOND) GROUP BY ALL",
            "SELECT game_id, min(amount) AS lo FROM clicks GROUP BY ALL",
            "SELECT ts, amount FROM clicks",
        ];
        let allowed = ["SELECT game_id, count(*) AS n, sum(amount) AS s, avg(amount) AS a FROM clicks GROUP BY ALL"];
        for sql in refused.iter().chain(&allowed) {
            let def = def_for(sql, false);
            let mut q = Circuit::query(&def.plan, &def);
            assert!(q.check(&def.plan).is_ok(), "{sql}: Kafka input is append-only");
            // The same view over a source that can retract (CDC).
            q.nodes[0].props.append_only = false;
            q.analyze();
            assert_eq!(q.check(&def.plan).is_err(), refused.contains(sql), "{sql}");
        }
    }
}
