//! A view as a DBSP circuit: the operator graph built from a compiled view, the pass that makes it incremental,
//! and the SQL one epoch runs.
//!
//! The graph follows Feldera's: operators in topological order, each reading output ports of earlier ones.
//! `Circuit::query` is the view as a query over whole collections (Q). `incrementalize` turns it into the
//! circuit that runs on changes, the way DBSP proves it can be done: wrap the query as D ∘ Q ∘ I (integrate
//! each source's changes into a collection, differentiate each result back into changes), then rewrite.
//!
//! The rewrite is Feldera's (`OptimizeIncrementalVisitor`): integrators only move forward.
//!
//! - A linear operator L (map, filter, window assignment, the late split) commutes with I: L ∘ I = I ∘ L.
//! - Any other operator S becomes its incremental form SΔ = D ∘ S ∘ I, so S ∘ I = I ∘ SΔ. SΔ keeps its state
//!   in a DuckLake table.
//! - Where an integrator reaches a differentiator they cancel: D ∘ I = id.
//!
//! What is left has no I or D: linear operators on changes plus incremental operators with state. State lives
//! only where the algebra needs it. Every operator's SQL is generated by `stage_steps` (in-memory staging,
//! before the epoch's transaction) and `commit_steps` (writes in the transaction). Linear operators fuse into
//! their consumer's statement where they can; the stateless SQL fragments the view compiler produces from
//! DuckDB's parse tree read named tables, so their inputs are materialized under those names.
//!
//! Layout: `frontend` turns SQL into Q, `passes` make it incremental, `codegen` turns the result into SQL
//! steps, `ir` holds the graph they share, and `ops` holds the operators, one file each.
